"""Migrations must not touch data through foreign keys (SQLite batch table rebuilds)."""

from collections.abc import AsyncIterator
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import Connection

from driftwood.db import Database, without_foreign_keys


@pytest.fixture
async def database(tmp_path: Path) -> AsyncIterator[Database]:
    database = Database(f"sqlite+aiosqlite:///{tmp_path}/driftwood.db")
    await database.migrate()
    yield database
    await database.dispose()


async def seed(database: Database) -> None:
    async with database.engine.begin() as connection:
        await connection.exec_driver_sql(
            "INSERT INTO users (id, issuer, subject, name, created_at, last_login_at) "
            "VALUES (1, 'https://idp', 'a', 'Ada', '2026-01-01', '2026-01-01')"
        )
        await connection.exec_driver_sql(
            "INSERT INTO sessions (token_hash, user_id, created_at, expires_at) "
            "VALUES ('h', 1, '2026-01-01', '2099-01-01')"
        )


def rebuild_users(connection: Connection) -> None:
    """What an autogenerated batch migration does to `users` for most column changes:
    copy it to a new table, drop the original (the dangerous part), rename."""
    with Operations(MigrationContext.configure(connection)).batch_alter_table(
        "users", recreate="always"
    ) as batch:
        batch.alter_column("name", existing_type=sa.String(255), nullable=True)


async def count_sessions(database: Database) -> int:
    async with database.engine.connect() as connection:
        return (await connection.exec_driver_sql("SELECT count(*) FROM sessions")).scalar_one()


async def test_rebuilding_a_table_keeps_the_rows_referencing_it(database: Database) -> None:
    await seed(database)
    async with database.engine.connect() as connection:
        await connection.run_sync(lambda c: without_foreign_keys(c, lambda: rebuild_users(c)))
    assert await count_sessions(database) == 1


async def test_with_enforcement_on_the_rebuild_would_cascade(database: Database) -> None:
    """The control for the test above: the hazard is real."""
    await seed(database)
    async with database.engine.begin() as connection:
        await connection.run_sync(rebuild_users)
    assert await count_sessions(database) == 0


async def test_enforcement_is_back_on_after_migrating(database: Database) -> None:
    # Every pooled connection, including the one the migration used.
    for _ in range(3):
        async with database.engine.connect() as connection:
            assert (await connection.exec_driver_sql("PRAGMA foreign_keys")).scalar_one() == 1


async def test_a_migration_that_breaks_foreign_keys_is_rolled_back(database: Database) -> None:
    await seed(database)

    def orphan_sessions(connection: Connection) -> None:
        connection.exec_driver_sql("DELETE FROM users")

    async with database.engine.connect() as connection:
        with pytest.raises(RuntimeError, match="break foreign keys"):
            await connection.run_sync(lambda c: without_foreign_keys(c, lambda: orphan_sessions(c)))
    async with database.engine.connect() as connection:
        assert (await connection.exec_driver_sql("SELECT count(*) FROM users")).scalar_one() == 1
